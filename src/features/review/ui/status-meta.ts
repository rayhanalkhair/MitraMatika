import type { ReviewCheck, ReviewQuestion } from "@/features/review/service/review";

export type DisplayStatus =
  ReviewQuestion["verification"]["status"] | "checking" | "waiting";

// What the job is doing, as far as the list cares: running (also queued or not yet known),
// deferred (waiting for the AI service) or finished (no more verification will happen).
export type JobState = "running" | "deferred" | "finished";

// "Sedang diperiksa" / "Menunggu pemeriksaan" only while the job is not finished and the question
// has no verification run; afterwards the stored status is shown.
export function displayStatus(
  verification: ReviewQuestion["verification"],
  jobState: JobState,
): DisplayStatus {
  if (verification.checked || jobState === "finished") return verification.status;
  return jobState === "deferred" ? "waiting" : "checking";
}

export function checkTypeKey(
  type: ReviewCheck["type"],
): "numeric" | "equivalent" | "equation" | "choice" | "other" {
  switch (type) {
    case "numeric_eval":
      return "numeric";
    case "expression_equivalent":
      return "equivalent";
    case "equation_solution":
      return "equation";
    case "choice_matches_answer":
      return "choice";
    default:
      return "other";
  }
}

// A first-version contradiction while the job is still running may be regenerated by the pipeline,
// so Setujui waits (the server refuses it too). Once a regeneration ran or failed, it is final.
export function awaitsRegeneration(
  verification: ReviewQuestion["verification"],
  jobState: JobState,
): boolean {
  return (
    verification.status === "ketidaksesuaian" &&
    !verification.regenerated &&
    !verification.regenerationFailed &&
    jobState !== "finished"
  );
}
