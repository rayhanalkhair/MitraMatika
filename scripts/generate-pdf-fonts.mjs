// Writes two modules under src/features/export/assets/fonts/ (plan 2026-11-22-react-pdf, decision 8):
//  - katex-fallback.generated.ts: three KaTeX fonts that draw the math symbols the body fonts lack;
//  - liberation.generated.ts: the eight committed Liberation Serif/Sans TTFs (SIL OFL 1.1, release
//    2.1.5), the PDF's body fonts. It is loaded with a dynamic import() so unrelated bundles do not
//    carry its 4 MB.
// Both are base64 inside the JS bundle: fonts must not reach a function through a file path, as
// traced assets do not reach every page function and any function that starts the runner may render
// an export. Run `node scripts/generate-pdf-fonts.mjs` after a katex upgrade or a font change; tests
// fail until you do.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const FONT_FILES = {
  main: "KaTeX_Main-Regular.ttf",
  ams: "KaTeX_AMS-Regular.ttf",
  math: "KaTeX_Math-Italic.ttf",
};

export const OUTPUT = join(
  "src",
  "features",
  "export",
  "assets",
  "fonts",
  "katex-fallback.generated.ts",
);

export const LIBERATION_VERSION = "2.1.5";
export const LIBERATION_DIR = join("src", "features", "export", "assets", "fonts");
export const LIBERATION_OUTPUT = join(LIBERATION_DIR, "liberation.generated.ts");
export const LIBERATION_FILES = {
  serif: {
    regular: "LiberationSerif-Regular.ttf",
    bold: "LiberationSerif-Bold.ttf",
    italic: "LiberationSerif-Italic.ttf",
    boldItalic: "LiberationSerif-BoldItalic.ttf",
  },
  sans: {
    regular: "LiberationSans-Regular.ttf",
    bold: "LiberationSans-Bold.ttf",
    italic: "LiberationSans-Italic.ttf",
    boldItalic: "LiberationSans-BoldItalic.ttf",
  },
};

/** The source of the Liberation module, from the TTFs committed under `root`. */
export function generateLiberationModule(root) {
  const dir = join(root, LIBERATION_DIR);
  const lines = Object.entries(LIBERATION_FILES).flatMap(([family, faces]) => [
    `  ${family}: {`,
    ...Object.entries(faces).map(
      ([face, file]) =>
        `    ${face}: "${readFileSync(join(dir, file)).toString("base64")}",`,
    ),
    "  },",
  ]);
  return [
    "// GENERATED by scripts/generate-pdf-fonts.mjs. Do not edit; run `node scripts/generate-pdf-fonts.mjs`.",
    `// Source: the Liberation fonts ${LIBERATION_VERSION} (SIL Open Font License 1.1, see OFL.txt), base64 of`,
    "// the eight .ttf files next to this module. Load it with a dynamic import().",
    "",
    "// Typed as plain strings so the 4 MB literals are not literal types.",
    `export const LIBERATION: { version: string; serif: { regular: string; bold: string; italic: string; boldItalic: string }; sans: { regular: string; bold: string; italic: string; boldItalic: string } } = {`,
    `  version: "${LIBERATION_VERSION}",`,
    ...lines,
    "};",
    "",
  ].join("\n");
}

/** The source of the generated module for the katex package installed under `root`. */
export function generateFontsModule(root) {
  const pkg = join(root, "node_modules", "katex");
  const { version, license } = JSON.parse(
    readFileSync(join(pkg, "package.json"), "utf8"),
  );
  const entries = Object.entries(FONT_FILES).map(
    ([key, file]) =>
      `  ${key}: "${readFileSync(join(pkg, "dist", "fonts", file)).toString("base64")}",`,
  );
  return [
    "// GENERATED by scripts/generate-pdf-fonts.mjs. Do not edit; run `node scripts/generate-pdf-fonts.mjs`.",
    `// Source: the katex package, version ${version}, licence ${license} (fonts KaTeX_Main-Regular,`,
    "// KaTeX_AMS-Regular and KaTeX_Math-Italic, base64 of the .ttf files).",
    "",
    "export const KATEX_FALLBACK: { version: string; main: string; ams: string; math: string } = {",
    `  version: "${version}",`,
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = process.cwd();
  writeFileSync(join(root, OUTPUT), generateFontsModule(root));
  console.log(`wrote ${OUTPUT}`);
  writeFileSync(join(root, LIBERATION_OUTPUT), generateLiberationModule(root));
  console.log(`wrote ${LIBERATION_OUTPUT}`);
}
