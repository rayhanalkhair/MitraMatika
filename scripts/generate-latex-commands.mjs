// Writes src/lib/latex-commands.generated.ts: every KaTeX command name that starts with n or t
// (the letters of the `\n` and `\t` escapes normalize-ai-text.ts removes outside maths), read from
// the installed KaTeX. KaTeX writes each name as a whole double-quoted string with an escaped
// backslash ("\\neq"), in function names, macros and symbols. Run after upgrading katex:
//   node scripts/generate-latex-commands.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Every command name (without the backslash) KaTeX defines whose name starts with one of `letters`. */
export function katexCommands(root, letters) {
  const source = readFileSync(
    join(root, "node_modules", "katex", "dist", "katex.mjs"),
    "utf8",
  );
  const names = new Set();
  for (const match of source.matchAll(/"\\\\([A-Za-z]+)"/g)) {
    if (letters.includes(match[1][0])) names.add(match[1]);
  }
  return [...names].sort();
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(fileURLToPath(import.meta.url), "..", "..");
  const names = katexCommands(root, "nt");
  const body = names.map((name) => `  "${name}",`).join("\n");
  writeFileSync(
    join(root, "src", "lib", "latex-commands.generated.ts"),
    `// Generated by scripts/generate-latex-commands.mjs from the installed KaTeX. Do not edit.\n` +
      `export const KATEX_N_T_COMMANDS: readonly string[] = [\n${body}\n];\n`,
  );
}
